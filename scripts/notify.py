import os, json, requests
from pathlib import Path

BASE_DIR = Path(__file__).resolve().parent
SCORES = BASE_DIR / "data" / "scores"
STATE = BASE_DIR / "data" / "state"; STATE.mkdir(parents=True, exist_ok=True)
MEAS = BASE_DIR / "measurements"
NOTIFIED_PATH = STATE / "notified.json"

def _load_notified() -> set:
    """Load the set of already notified anomaly keys to avoid duplicate alerts"""
    if NOTIFIED_PATH.exists():
        return set(json.loads(NOTIFIED_PATH.read_text(encoding="utf-8")))
    return set()

def _save_notified(keys: set):
    NOTIFIED_PATH.write_text(json.dumps(sorted(keys), indent=2), encoding="utf-8")

def _send_telegram(token: str, chat: str, ticker: str, anomaly: dict):
    """Send a single anomaly alert to Telegram. Non blocking on failure"""
    snippet = (anomaly.get("worst_snippet") or "No context available").replace("*", "").replace("_", "")

    # Ground truth financial return validation for the anomaly period
    stock_ret = anomaly.get("stock_return_pct")
    if stock_ret is None:
        stock_ret_str = "0%"
    elif isinstance(stock_ret, (int, float)):
        stock_ret_str = f"{stock_ret:+.2f}%" if stock_ret != 0 else "0%"
    else:
        stock_ret_str = f"{stock_ret}%"

    text = (
        "*SEC 8K Tone Anomaly Alert*\n\n"
        f"*Ticker:* `{ticker}` ({anomaly['year']})\n"
        f"*Z Score:* `{anomaly['z']}` | *Drift:* `{anomaly.get('drift', 'N/A')}`\n"
        f"*Annual Equity Return:* {stock_ret_str}\n\n"
        f"*Key Negative Excerpt:*\n> _{snippet}_"
    )
    try:
        r = requests.post(
            f"https://api.telegram.org/bot{token}/sendMessage",
            json={"chat_id": chat, "text": text, "parse_mode": "Markdown"},
            timeout=15,
        )
        r.raise_for_status()
        print(f"  [SUCCESS] Alert sent for {ticker} ({anomaly['year']})")
    except Exception as e:
        # Non blocking: log the error but never crash the pipeline
        print(f"  [WARNING] Failed to send alert for {ticker}: {e}")

def run():
    token = os.environ.get("TELEGRAM_TOKEN")
    chat = os.environ.get("TELEGRAM_CHAT")

    if not token or not chat:
        print("[INFO] Notifications disabled (missing secrets)")
        return

    # Load anomaly report generated by anomalies.py
    report_path = MEAS / "anomalies.json"
    if not report_path.exists():
        print("[INFO] No anomaly report found, skipping notifications")
        return

    report = json.loads(report_path.read_text(encoding="utf-8"))
    notified = _load_notified()
    new_count = 0

    for ticker, events in report.items():
        for anomaly in events:
            key = f"{ticker}_{anomaly['year']}"
            if key in notified:
                continue  # Already sent, skip duplicate
            _send_telegram(token, chat, ticker, anomaly)
            notified.add(key)
            new_count += 1

    _save_notified(notified)
    print(f"[INFO] Notifications complete: {new_count} new alert(s) sent")

if __name__ == "__main__":
    run()
